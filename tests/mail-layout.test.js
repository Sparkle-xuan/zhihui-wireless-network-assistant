const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const script = fs.readFileSync(require('node:path').join(__dirname,'../static/app.js'),'utf8');
const start=script.indexOf("document.querySelectorAll('[data-send]')");
const end=script.indexOf("$('#mail-form').addEventListener('submit'",start);
assert.ok(start>=0 && end>start);
let submitted=0, reported=0;
const button={dataset:{send:'weekly'},addEventListener(type,fn){this.click=fn}};
const status={textContent:''}, details={open:false};
const form={valid:false,checkValidity(){return this.valid},reportValidity(){reported++},requestSubmit(){submitted++},elements:{sender:{value:'user@qq.com'},auth_code:{value:'',focus(){}}}};
const nodes={'#mail-form':form,'#weekly-mail-status':status,'#mail-details':details,'#mail-panel':{scrollIntoView(){}}};
const context={document:{querySelectorAll(){return [button]}},$:s=>nodes[s],savedSender:'',mailSubmitRequested:false};
vm.runInNewContext(script.slice(start,end),context);
button.click();
assert.equal(submitted,0);assert.equal(reported,1);assert.equal(details.open,true);
form.valid=true;button.click();assert.equal(submitted,0);assert.match(status.textContent,/授权码/);
context.savedSender='USER@qq.com';button.click();assert.equal(submitted,1);
form.elements.sender.value='other@qq.com';button.click();assert.equal(submitted,1);
form.elements.auth_code.value='temporary-code';button.click();assert.equal(submitted,2);
console.log('报告旁发送按钮的必填和授权码校验通过');
